export function SignInForm({ callbackUrl }: { callbackUrl: string }) {
  const router = useRouter();
  // Defense-in-depth: never navigate off-origin even if a bad value slips in.
  const destination = safeCallbackUrl(callbackUrl);
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [needsVerification, setNeedsVerification] = useState(false);
  const [loading, setLoading] = useState(false);

  async function onSubmit(e: React.FormEvent) {
    e.preventDefault();
    setError(null);
    setNeedsVerification(false);
    setLoading(true);

    const res = await signIn("credentials", {
      email,
      password,
      redirect: false,
    });

    setLoading(false);

    if (res?.error) {
      // Valid credentials but unverified email — prompt to verify instead of
      // showing a misleading "invalid credentials" message.
      if (res.code === "email_not_verified") {
        setNeedsVerification(true);
        setError("Please verify your email before signing in.");
      } else if (res.code?.startsWith("rate_limited")) {
        // auth.ts packs the retry time into the code as `rate_limited_<minutes>`.
        const minutes = res.code.match(/_(\d+)$/)?.[1];
        const when = minutes
          ? `in ${minutes} minute${minutes === "1" ? "" : "s"}`
          : "later";
        toast(`Too many sign-in attempts. Please try again ${when}.`, "error");
      } else {
        setError("Invalid email or password.");
      }
      return;
    }

    router.push(destination);
    router.refresh();
  }

  return (
    <div className="space-y-4">
      <Button
        type="button"
        variant="outline"
        className="w-full"
        onClick={() => signIn("github", { callbackUrl: destination })}
      >
        <GitHubLogo className="size-4" />
        Sign in with GitHub
      </Button>

      <div className="flex items-center gap-3 text-xs text-muted-foreground">
        <span className="h-px flex-1 bg-border" />
        or
        <span className="h-px flex-1 bg-border" />
      </div>

      <form onSubmit={onSubmit} className="space-y-3">
        <div className="space-y-1.5">
          <label htmlFor="email" className="text-sm font-medium">
            Email
          </label>
          <Input
            id="email"
            type="email"
            autoComplete="email"
            required
            value={email}
            onChange={(e) => setEmail(e.target.value)}
          />
        </div>

        <div className="space-y-1.5">
          <div className="flex items-center justify-between">
            <label htmlFor="password" className="text-sm font-medium">
              Password
            </label>
            <Link
              href="/forgot-password"
              className="text-xs text-muted-foreground hover:text-foreground hover:underline"
            >
              Forgot password?
            </Link>
          </div>
          <Input
            id="password"
            type="password"
            autoComplete="current-password"
            required
            value={password}
            onChange={(e) => setPassword(e.target.value)}
          />
        </div>

        {error && <p className="text-sm text-destructive">{error}</p>}

        <Button type="submit" className="w-full" disabled={loading}>
          {loading ? "Signing in…" : "Sign in"}
        </Button>
      </form>

      {needsVerification && <ResendVerificationForm email={email} />}

      <p className="text-center text-sm text-muted-foreground">
        Don&apos;t have an account?{" "}
        <Link href="/register" className="text-primary hover:underline">
          Register
        </Link>
      </p>
    </div>
  );
}
